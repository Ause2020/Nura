const STANDARD_EN: Record<string, string> = {
  custom: "Custom",
  haccp_codex: "HACCP Codex",
  iso22000: "ISO 22000:2018",
  fssc22000: "FSSC 22000",
  brc: "BRC / BRCGS",
  fda_fsma: "FDA FSMA",
};

export function localizeSection(section: string, lang: ExportLang): string {
  if (lang !== "en") return section;
  return SECTION_EN[section] ?? section;
}

export function localizeStandard(standard: string, lang: ExportLang): string {
  if (lang === "en") {
    return STANDARD_EN[standard] ?? standard.replace(/_/g, " ").toUpperCase();
  }
  if (standard === "custom") return "Personalizada";
  return STANDARD_EN[standard] ?? standard;
}

export function dateLocale(lang: ExportLang): string {
  return lang === "en" ? "en-US" : "es";
}
